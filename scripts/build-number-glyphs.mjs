// Build-time only: workers import masks, not PNG decoders or network loaders.
import fs from 'node:fs';
import {createHash} from 'node:crypto';
import {readPNG} from '../tests/png-fixture.mjs';
const timer=[],count=[],sprites=[],words=[],sources=[],seen=new Map();
function fingerprint(bits,w,h){
 let s='';for(let y=0;y<12;y++)for(let x=0;x<10;x++)s+=bits[Math.min(h-1,Math.floor((y+.5)*h/12))*w+Math.min(w-1,Math.floor((x+.5)*w/10))];
 return s;
}
for(const family of ['buff_time_1','buff_time_2','count'])for(let digit=0;digit<10;digit++){
 const name=family==='count'?`count_num/count_${digit}.png`:`${family}/${digit}.png`;
 const path=new URL('../icon/number/'+name,import.meta.url),img=readPNG(path);
 sources.push([name,createHash('sha256').update(fs.readFileSync(path)).digest('hex')]);
 if(family==='count')sprites.push({digit,w:img.w,h:img.h,rgba:[...img.rgba]});
 let minX=img.w,minY=img.h,maxX=-1,maxY=-1;
 for(let y=0;y<img.h;y++)for(let x=0;x<img.w;x++){
  const p=(y*img.w+x)*4,a=img.rgba[p+3]/255,r=img.rgba[p]*a,g=img.rgba[p+1]*a,b=img.rgba[p+2]*a;
  if(family==='count' ? r>160&&g>160&&(b>160||r-b>=40&&g-b>=25) : r>115&&g>94&&Math.min(r,g)-b>65){minX=Math.min(minX,x);maxX=Math.max(maxX,x);minY=Math.min(minY,y);maxY=Math.max(maxY,y);}
 }
 const coreW=maxX-minX+1,coreH=maxY-minY+1;
 const scales=family==='count'?[1]:[1,1.25,45/32,1.5,1.75,2];
 for(const scale of scales){
  const phases=Number.isInteger(scale)?[0]:scale===1.25?[0,1,2,3]:[0,1];
  for(const px of phases)for(const py of phases){
   const cw=img.w+8,ch=img.h+8,w=Math.ceil(cw*scale),h=Math.ceil(ch*scale),rgb=new Float32Array(w*h*3);
   for(let y=0;y<h;y++)for(let x=0;x<w;x++){
    const u=(x+.5)/scale-.5-2-px,v=(y+.5)/scale-.5-2-py;
    const sx=Math.floor(u),sy=Math.floor(v),dx=u-sx,dy=v-sy;
    for(const [ox,oy,weight] of [[0,0,(1-dx)*(1-dy)],[1,0,dx*(1-dy)],[0,1,(1-dx)*dy],[1,1,dx*dy]]){
     const xx=sx+ox,yy=sy+oy;if(xx<0||xx>=img.w||yy<0||yy>=img.h)continue;
     const p=(yy*img.w+xx)*4,a=img.rgba[p+3]/255;
     for(let c=0;c<3;c++)rgb[(y*w+x)*3+c]+=img.rgba[p+c]*a*weight;
    }
   }
   for(const threshold of [96,115,140,175,215]){
    const bits=new Uint8Array(w*h);let left=w,right=-1,top=h,bottom=-1;
    for(let y=0;y<h;y++)for(let x=0;x<w;x++){
     const p=(y*w+x)*3,r=rgb[p],g=rgb[p+1],b=rgb[p+2];
     const ink=family==='count'?r>threshold&&g>threshold&&(b>threshold||r-b>=40&&g-b>=25):r>threshold&&g>threshold*.8&&Math.min(r,g)-b>65;
     if(ink){bits[y*w+x]=1;left=Math.min(left,x);right=Math.max(right,x);top=Math.min(top,y);bottom=Math.max(bottom,y);}
    }
    if(right<left)continue;
    const bw=right-left+1,bh=bottom-top+1,cropped=[];
    if(bh<coreH*scale*.8 || bw<coreW*scale*.6)continue;
    for(let y=top;y<=bottom;y++)for(let x=left;x<=right;x++)cropped.push(bits[y*w+x]);
    const normalized=fingerprint(cropped,bw,bh),key=(family==='count'?'count':'timer')+digit+':'+normalized;
    const old=seen.get(key);
    if(old){if(!old.shapes.some(([w,h])=>w===bw&&h===bh))old.shapes.push([bw,bh]);continue;}
    const entry={digit,bits:normalized,shapes:[[bw,bh]],source:name};seen.set(key,entry);
    (family==='count'?count:timer).push(entry);
   }
  }
 }
}
const wordDir=new URL('../icon/number/count_num/',import.meta.url);
for(const name of fs.readdirSync(wordDir).sort()){
 const match=/^count_(\d+)\.png$/.exec(name);
 if(!match)continue;
 const path=new URL(name,wordDir),{w,h,rgba}=readPNG(path);
 if(Number(match[1])>=10)sources.push(['count_num/'+name,createHash('sha256').update(fs.readFileSync(path)).digest('hex')]);
 // Ignore translucent borders. The opaque shadow and strokes survive HUD tinting.
 const mask=Array.from({length:w*h},(_,i)=>rgba[i*4+3]<250 ? ' ' : rgba[i*4]===0 ? '0' : '1').join('');
 words.push({count:Number(match[1]),w,h,mask});
}
fs.writeFileSync(new URL('../js/data/number-glyphs.js',import.meta.url),
 '// Generated by scripts/build-number-glyphs.mjs from icon/number PNGs.\n'+
 'export const TIMER_IMAGE_GLYPHS='+JSON.stringify(timer)+';\n'+
 'export const COUNT_IMAGE_GLYPHS='+JSON.stringify(count)+';\n'+
 'export const COUNT_IMAGE_SPRITES='+JSON.stringify(sprites)+';\n'+
 'export const COUNT_WORD_MASKS='+JSON.stringify(words)+';\n'+
 'export const NUMBER_GLYPH_SOURCES='+JSON.stringify(sources)+';\n');
console.log(`Built ${timer.length} timer and ${count.length} quantity masks from ${sources.length} PNGs.`);
